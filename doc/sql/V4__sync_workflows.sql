CREATE TABLE sync_tasks(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(200) NOT NULL, description VARCHAR(2000) DEFAULT '' NOT NULL,
 state VARCHAR(16) DEFAULT 'DRAFT' NOT NULL CHECK(state IN('DRAFT','READY')),
 schedule_enabled BOOLEAN DEFAULT FALSE NOT NULL, cron VARCHAR(100) NOT NULL,
 timezone VARCHAR(100) NOT NULL, config_revision BIGINT DEFAULT 1 NOT NULL,
 next_fire_at TIMESTAMP WITH TIME ZONE, deleted_at TIMESTAMP WITH TIME ZONE,
 created_by BIGINT REFERENCES app_users(id), updated_by BIGINT REFERENCES app_users(id),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE sync_task_steps(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id BIGINT NOT NULL REFERENCES sync_tasks(id),
 step_key VARCHAR(100) NOT NULL, position INTEGER NOT NULL, component_type VARCHAR(20) NOT NULL,
 name VARCHAR(200) NOT NULL, config_json CLOB NOT NULL, secret_bundle_id BIGINT REFERENCES sync_secret_bundles(id),
 UNIQUE(task_id,step_key),UNIQUE(task_id,position),
 CHECK(component_type IN('KEYSTORE','TRUSTSTORE','SFTP','HTTP'))
);
CREATE TABLE sync_step_servers(step_id BIGINT NOT NULL REFERENCES sync_task_steps(id),server_id BIGINT NOT NULL REFERENCES managed_servers(id),PRIMARY KEY(step_id,server_id));
CREATE TABLE sync_step_certificates(
 step_id BIGINT NOT NULL REFERENCES sync_task_steps(id),source_asset_id BIGINT NOT NULL REFERENCES certificate_assets(id),
 material_id BIGINT NOT NULL REFERENCES certificate_materials(id),entry_alias VARCHAR(200) NOT NULL,entry_role VARCHAR(16) NOT NULL,
 PRIMARY KEY(step_id,entry_alias)
);
CREATE INDEX ix_sync_cert_material ON sync_step_certificates(material_id);
CREATE TABLE sync_step_inputs(step_id BIGINT PRIMARY KEY REFERENCES sync_task_steps(id),source_step_id BIGINT NOT NULL REFERENCES sync_task_steps(id));
CREATE TABLE sync_runs(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,task_id BIGINT NOT NULL REFERENCES sync_tasks(id),
 trigger_type VARCHAR(16) NOT NULL,scheduled_for TIMESTAMP WITH TIME ZONE,request_key VARCHAR(100),task_revision BIGINT NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN('QUEUED','RUNNING','SUCCESS','FAILED','INTERRUPTED')),
 snapshot_json CLOB NOT NULL,lease_owner VARCHAR(100),lease_until TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,started_at TIMESTAMP WITH TIME ZONE,finished_at TIMESTAMP WITH TIME ZONE,error_summary VARCHAR(2000),
 UNIQUE(task_id,scheduled_for),UNIQUE(task_id,request_key)
);
CREATE INDEX ix_sync_runs_poll ON sync_runs(status,id);
CREATE TABLE sync_run_certificates(run_id BIGINT NOT NULL REFERENCES sync_runs(id),source_asset_id BIGINT NOT NULL REFERENCES certificate_assets(id),material_id BIGINT NOT NULL REFERENCES certificate_materials(id),fingerprint CHAR(64) NOT NULL,PRIMARY KEY(run_id,source_asset_id,material_id));
CREATE TABLE sync_run_servers(run_id BIGINT NOT NULL REFERENCES sync_runs(id),server_id BIGINT NOT NULL REFERENCES managed_servers(id),server_config_id BIGINT NOT NULL REFERENCES managed_server_configs(id),PRIMARY KEY(run_id,server_id));
CREATE TABLE sync_run_secret_bundles(run_id BIGINT NOT NULL REFERENCES sync_runs(id),secret_bundle_id BIGINT NOT NULL REFERENCES sync_secret_bundles(id),PRIMARY KEY(run_id,secret_bundle_id));
CREATE TABLE sync_run_steps(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id BIGINT NOT NULL REFERENCES sync_runs(id),step_key VARCHAR(100) NOT NULL,position INTEGER NOT NULL,
 component_type VARCHAR(20) NOT NULL,name VARCHAR(200) NOT NULL,status VARCHAR(16) DEFAULT 'PENDING' NOT NULL,
 started_at TIMESTAMP WITH TIME ZONE,finished_at TIMESTAMP WITH TIME ZONE,result_json CLOB,error_summary VARCHAR(2000),
 UNIQUE(run_id,step_key),CHECK(status IN('PENDING','RUNNING','SUCCESS','FAILED','SKIPPED'))
);
