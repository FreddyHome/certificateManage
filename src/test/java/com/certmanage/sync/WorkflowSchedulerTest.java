package com.certmanage.sync;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

import com.certmanage.common.ExecutionLog;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.time.OffsetDateTime;
import java.util.Map;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.support.TransactionTemplate;

/**
 * @description 验证定时推进、入队失败记录与不重试规则，数据库完全独立于生产库。
 * @author Freddy
 * @date 2026-11-12
 */
class WorkflowSchedulerTest {
  /**
   * @description 调度先提交下一次触发时间，再尝试单次入队，业务拒绝时保留失败快照与日志。
   * @author Freddy
   * @date 2026-11-12
   */
  @Test
  void advancesCronAndRecordsRejectedEnqueueWithoutRetry() {
    var source =
        new DriverManagerDataSource(
            "jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", "");
    var db = new JdbcTemplate(source);
    db.execute("create table sync_guard(id int primary key)");
    db.execute("insert into sync_guard values(1)");
    db.execute(
        "create table sync_tasks(id bigint primary key,name varchar,description varchar,config_revision bigint,state varchar,schedule_enabled boolean,cron varchar,timezone varchar,next_fire_at timestamp with time zone,deleted_at timestamp with time zone,schedule_json clob)");
    db.execute(
        "create table sync_task_steps(task_id bigint,position int,step_key varchar,name varchar,component_type varchar,config_json varchar,secret_bundle_id bigint)");
    db.execute(
        "create table sync_runs(id bigint generated by default as identity primary key,task_id bigint,trigger_type varchar,scheduled_for timestamp with time zone,task_revision bigint,status varchar,snapshot_json varchar,finished_at timestamp with time zone,error_summary varchar)");
    var fire = OffsetDateTime.parse("2020-01-01T00:00:00Z");
    db.update(
        "insert into sync_tasks values(1,'任务','',7,'READY',true,'0 0 2 * * *','Asia/Shanghai',?,null,null)",
        fire);
    var logs = mock(ExecutionLog.class);
    var validator = mock(WorkflowValidator.class);
    var service =
        new WorkflowService(
            db,
            new TransactionTemplate(new DataSourceTransactionManager(source)),
            new ObjectMapper(),
            null,
            null,
            validator,
            null,
            logs);
    doThrow(new IllegalArgumentException("证书配置不可用")).when(validator).prepare(anyList(), eq(true));

    service.schedule();

    verify(validator, times(1)).prepare(anyList(), eq(true));
    assertThat(
            db.queryForObject(
                "select next_fire_at from sync_tasks where id=1", OffsetDateTime.class))
        .isAfter(OffsetDateTime.now());
    var failed = db.queryForMap("select * from sync_runs");
    assertThat(failed)
        .containsEntry("STATUS", "FAILED")
        .containsEntry("TRIGGER_TYPE", "SCHEDULED")
        .containsEntry("TASK_REVISION", 7L)
        .containsEntry("SNAPSHOT_JSON", "{\"steps\":[]}");
    assertThat((OffsetDateTime) failed.get("SCHEDULED_FOR")).isEqualTo(fire);
    verify(logs)
        .append(
            eq("SYNC"),
            eq("SCHEDULE_REJECTED"),
            eq("FAILURE"),
            eq("scheduler"),
            anyLong(),
            isNull(),
            eq("SYNC_TASK"),
            eq(1L),
            anyString(),
            eq(Map.of()));
    service.schedule();
    assertThat(db.queryForObject("select count(*) from sync_runs", Integer.class)).isEqualTo(1);
    verify(validator, times(1)).prepare(anyList(), eq(true));
  }
}
