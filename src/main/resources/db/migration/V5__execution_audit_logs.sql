CREATE TABLE execution_logs(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 occurred_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 source VARCHAR(32) NOT NULL,event_code VARCHAR(100) NOT NULL,outcome VARCHAR(16) NOT NULL,
 actor_name VARCHAR(100) NOT NULL,run_id BIGINT,step_key VARCHAR(100),
 target_type VARCHAR(32),target_id BIGINT,message VARCHAR(2000) NOT NULL,detail_json CLOB NOT NULL,
 CHECK(outcome IN('STARTED','SUCCESS','FAILURE','SKIPPED','INTERRUPTED','INFO'))
);
CREATE INDEX ix_exec_log_time ON execution_logs(occurred_at,id);
CREATE INDEX ix_exec_log_run ON execution_logs(run_id,id);
CREATE INDEX ix_exec_log_source ON execution_logs(source,outcome,id);
