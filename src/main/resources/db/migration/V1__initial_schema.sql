-- H2 2.x; fresh schema only. No plaintext secrets or default password in SQL.
CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 enabled BOOLEAN DEFAULT TRUE NOT NULL,
 auth_epoch BIGINT DEFAULT 0 NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE app_roles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 role_code VARCHAR(50) NOT NULL UNIQUE,
 role_name VARCHAR(100) NOT NULL
);
CREATE TABLE app_user_roles (
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 role_id BIGINT NOT NULL REFERENCES app_roles(id),
 PRIMARY KEY(user_id,role_id)
);
CREATE TABLE app_sessions (
 token_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 auth_epoch BIGINT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_sessions_expiry ON app_sessions(expires_at);
CREATE INDEX ix_sessions_user ON app_sessions(user_id);
CREATE TABLE app_bootstrap (
 bootstrap_key VARCHAR(100) PRIMARY KEY,
 completed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_name VARCHAR(200) NOT NULL,
 name_key VARCHAR(300) NOT NULL UNIQUE,
 description VARCHAR(2000),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT ck_customer_name CHECK(CHAR_LENGTH(TRIM(customer_name))>0)
);
CREATE TABLE certificate_materials (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fingerprint_sha256 CHAR(64) NOT NULL UNIQUE,
 certificate_der BLOB NOT NULL,
 common_name VARCHAR(1024) NOT NULL,
 subject_dn CLOB NOT NULL,
 issuer_dn CLOB NOT NULL,
 serial_hex VARCHAR(256) NOT NULL,
 not_before TIMESTAMP WITH TIME ZONE NOT NULL,
 not_after TIMESTAMP WITH TIME ZONE NOT NULL,
 public_key_algorithm VARCHAR(100) NOT NULL,
 public_key_bits INTEGER,
 signature_algorithm VARCHAR(100) NOT NULL,
 spki_sha256 CHAR(64) NOT NULL,
 san_json CLOB,
 is_ca BOOLEAN NOT NULL,
 path_length INTEGER,
 key_usage_json CLOB,
 extended_key_usage_json CLOB,
 subject_key_identifier VARCHAR(1024),
 authority_key_identifier VARCHAR(1024),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT ck_material_time CHECK(not_after>not_before),
 CONSTRAINT ck_material_path CHECK(path_length IS NULL OR (is_ca=TRUE AND path_length>=0))
);
CREATE INDEX ix_material_expiry ON certificate_materials(not_after,id);
CREATE TABLE certificate_assets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 material_id BIGINT NOT NULL REFERENCES certificate_materials(id),
 owner_type VARCHAR(16) NOT NULL,
 customer_id BIGINT REFERENCES customers(id),
 scope_key VARCHAR(40) NOT NULL,
 purpose VARCHAR(16) NOT NULL,
 certificate_kind VARCHAR(16) NOT NULL,
 chain_depth INTEGER,
 issuer_material_id BIGINT REFERENCES certificate_materials(id),
 issuer_asset_id BIGINT REFERENCES certificate_assets(id),
 source_type VARCHAR(16) NOT NULL,
 business_description VARCHAR(1000),
 remark VARCHAR(2000),
 created_by BIGINT NOT NULL REFERENCES app_users(id),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_asset_scope UNIQUE(scope_key,material_id),
 CONSTRAINT uq_asset_owner UNIQUE(id,owner_type),
 CONSTRAINT ck_asset_owner CHECK((owner_type='OWN' AND customer_id IS NULL AND scope_key='OWN') OR (owner_type='CUSTOMER' AND customer_id IS NOT NULL AND scope_key='CUSTOMER:' || CAST(customer_id AS VARCHAR))),
 CONSTRAINT ck_asset_purpose CHECK(purpose IN ('AS2','HTTPS','GENERAL')),
 CONSTRAINT ck_asset_kind CHECK(certificate_kind IN ('ROOT','INTERMEDIATE','LEAF')),
 CONSTRAINT ck_customer_leaf CHECK(owner_type<>'CUSTOMER' OR certificate_kind='LEAF'),
 CONSTRAINT ck_asset_depth CHECK(chain_depth IS NULL OR chain_depth>=1),
 CONSTRAINT ck_root_depth CHECK(certificate_kind<>'ROOT' OR chain_depth=1),
 CONSTRAINT ck_asset_source CHECK(source_type IN ('IMPORTED','GENERATED'))
);
CREATE INDEX ix_asset_owner_kind ON certificate_assets(owner_type,certificate_kind,id);
CREATE INDEX ix_asset_customer ON certificate_assets(customer_id,purpose,id);
CREATE INDEX ix_asset_material ON certificate_assets(material_id);
CREATE TABLE asset_chain_nodes (
 asset_id BIGINT NOT NULL REFERENCES certificate_assets(id),
 node_position INTEGER NOT NULL,
 material_id BIGINT NOT NULL REFERENCES certificate_materials(id),
 PRIMARY KEY(asset_id,node_position),
 CONSTRAINT uq_chain_material UNIQUE(asset_id,material_id),
 CONSTRAINT ck_chain_position CHECK(node_position>=1)
);
CREATE INDEX ix_chain_material ON asset_chain_nodes(material_id);
CREATE TABLE private_keys (
 own_asset_id BIGINT PRIMARY KEY,
 owner_type VARCHAR(16) DEFAULT 'OWN' NOT NULL,
 ciphertext BLOB NOT NULL,
 nonce VARBINARY(12) NOT NULL,
 encryption_key_id VARCHAR(100) NOT NULL,
 encryption_algorithm VARCHAR(32) DEFAULT 'AES-256-GCM' NOT NULL,
 public_key_algorithm VARCHAR(100) NOT NULL,
 spki_sha256 CHAR(64) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT ck_private_owner CHECK(owner_type='OWN'),
 CONSTRAINT ck_private_nonce CHECK(OCTET_LENGTH(nonce)=12),
 CONSTRAINT fk_private_own FOREIGN KEY(own_asset_id,owner_type) REFERENCES certificate_assets(id,owner_type)
);
CREATE TABLE smtp_config (
 id SMALLINT PRIMARY KEY,
 smtp_host VARCHAR(255) NOT NULL,
 smtp_port INTEGER NOT NULL,
 tls_mode VARCHAR(16) NOT NULL,
 smtp_username VARCHAR(320),
 credential_ciphertext BLOB,
 credential_nonce VARBINARY(12),
 encryption_key_id VARCHAR(100),
 sender_address VARCHAR(320) NOT NULL,
 sender_name VARCHAR(200),
 config_revision BIGINT DEFAULT 0 NOT NULL,
 updated_by BIGINT NOT NULL REFERENCES app_users(id),
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT ck_smtp_single CHECK(id=1),
 CONSTRAINT ck_smtp_port CHECK(smtp_port BETWEEN 1 AND 65535),
 CONSTRAINT ck_smtp_tls CHECK(tls_mode IN ('STARTTLS','TLS')),
 CONSTRAINT ck_smtp_secret CHECK((credential_ciphertext IS NULL AND credential_nonce IS NULL AND encryption_key_id IS NULL) OR (credential_ciphertext IS NOT NULL AND credential_nonce IS NOT NULL AND encryption_key_id IS NOT NULL AND OCTET_LENGTH(credential_nonce)=12))
);
CREATE TABLE notification_policy (
 id SMALLINT PRIMARY KEY,
 enabled BOOLEAN DEFAULT FALSE NOT NULL,
 timezone_id VARCHAR(64) NOT NULL,
 scan_time TIME NOT NULL,
 warning_days INTEGER NOT NULL,
 include_ca BOOLEAN NOT NULL,
 config_revision BIGINT DEFAULT 0 NOT NULL,
 updated_by BIGINT NOT NULL REFERENCES app_users(id),
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT ck_policy_single CHECK(id=1),
 CONSTRAINT ck_warning_days CHECK(warning_days>=0)
);
CREATE TABLE notification_thresholds (
 policy_id SMALLINT NOT NULL REFERENCES notification_policy(id),
 threshold_days INTEGER NOT NULL,
 PRIMARY KEY(policy_id,threshold_days),
 CONSTRAINT ck_threshold_days CHECK(threshold_days>=0)
);
CREATE TABLE notification_recipients (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 policy_id SMALLINT NOT NULL REFERENCES notification_policy(id),
 email_address VARCHAR(320) NOT NULL,
 email_key VARCHAR(320) NOT NULL,
 CONSTRAINT uq_policy_recipient UNIQUE(policy_id,email_key)
);
CREATE TABLE notification_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES certificate_assets(id),
 policy_id SMALLINT NOT NULL REFERENCES notification_policy(id),
 threshold_days INTEGER NOT NULL,
 recipient_address VARCHAR(320) NOT NULL,
 recipient_key VARCHAR(320) NOT NULL,
 not_after_snapshot TIMESTAMP WITH TIME ZONE NOT NULL,
 cn_snapshot VARCHAR(1024) NOT NULL,
 customer_snapshot VARCHAR(200),
 purpose_snapshot VARCHAR(16) NOT NULL,
 delivery_status VARCHAR(16) DEFAULT 'PENDING' NOT NULL,
 attempts INTEGER DEFAULT 0 NOT NULL,
 next_attempt_at TIMESTAMP WITH TIME ZONE,
 lease_owner VARCHAR(100),
 lease_until TIMESTAMP WITH TIME ZONE,
 message_id VARCHAR(255) NOT NULL UNIQUE,
 error_code VARCHAR(100),
 error_message VARCHAR(2000),
 sent_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_delivery UNIQUE(asset_id,not_after_snapshot,threshold_days,recipient_key),
 CONSTRAINT ck_delivery_status CHECK(delivery_status IN ('PENDING','SENDING','SENT','RETRY_WAIT','FAILED')),
 CONSTRAINT ck_delivery_attempts CHECK(attempts>=0 AND threshold_days>=0)
);
CREATE INDEX ix_delivery_poll ON notification_deliveries(delivery_status,next_attempt_at,lease_until);
CREATE INDEX ix_delivery_asset ON notification_deliveries(asset_id,created_at);
CREATE TABLE notification_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 delivery_id BIGINT NOT NULL REFERENCES notification_deliveries(id),
 attempt_no INTEGER NOT NULL,
 started_at TIMESTAMP WITH TIME ZONE NOT NULL,
 finished_at TIMESTAMP WITH TIME ZONE,
 outcome VARCHAR(16) NOT NULL,
 error_code VARCHAR(100),
 error_message VARCHAR(2000),
 CONSTRAINT uq_delivery_attempt UNIQUE(delivery_id,attempt_no),
 CONSTRAINT ck_attempt_no CHECK(attempt_no>0),
 CONSTRAINT ck_attempt_outcome CHECK(outcome IN ('STARTED','SUCCESS','FAILURE','UNKNOWN'))
);
CREATE TABLE scheduler_state (
 task_key VARCHAR(100) PRIMARY KEY,
 lease_owner VARCHAR(100),
 lease_until TIMESTAMP WITH TIME ZONE,
 last_success_at TIMESTAMP WITH TIME ZONE,
 last_scan_date DATE
);
CREATE TABLE operation_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES app_users(id),
 operation_type VARCHAR(32) NOT NULL,
 request_key VARCHAR(100) NOT NULL,
 payload_digest CHAR(64) NOT NULL,
 asset_id BIGINT NOT NULL REFERENCES certificate_assets(id),
 response_json CLOB NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_operation_request UNIQUE(actor_id,operation_type,request_key),
 CONSTRAINT ck_operation_type CHECK(operation_type IN ('IMPORT','ISSUE'))
);
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT REFERENCES app_users(id),
 actor_name VARCHAR(100),
 action_code VARCHAR(100) NOT NULL,
 target_type VARCHAR(100) NOT NULL,
 target_id VARCHAR(100),
 outcome VARCHAR(16) NOT NULL,
 request_id VARCHAR(100),
 detail_summary VARCHAR(2000),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT ck_audit_outcome CHECK(outcome IN ('SUCCESS','FAILURE'))
);
CREATE INDEX ix_audit_time ON audit_events(created_at,id);
