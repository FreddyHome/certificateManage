import './element-plus-styles';
import type { App } from 'vue';
import {
  ElAlert,
  ElAside,
  ElButton,
  ElCard,
  ElCheckbox,
  ElCheckboxGroup,
  ElCollapse,
  ElCollapseItem,
  ElContainer,
  ElDatePicker,
  ElDescriptions,
  ElDescriptionsItem,
  ElDialog,
  ElDrawer,
  ElDropdown,
  ElDropdownItem,
  ElDropdownMenu,
  ElForm,
  ElFormItem,
  ElHeader,
  ElInput,
  ElInputNumber,
  ElMain,
  ElMenu,
  ElMenuItem,
  ElOption,
  ElPagination,
  ElRadio,
  ElRadioButton,
  ElRadioGroup,
  ElSelect,
  ElSubMenu,
  ElSwitch,
  ElTabPane,
  ElTable,
  ElTableColumn,
  ElTabs,
  ElTag,
  ElTimePicker,
  ElTimeline,
  ElTimelineItem,
  ElLoading,
  ElMessage,
  ElMessageBox,
  provideGlobalConfig,
} from 'element-plus';
import zhCn from 'element-plus/es/locale/lang/zh-cn';

/** 注册页面实际使用的组件，并为独立消息服务提供同一中文配置。 */
export function installElementPlus(app: App) {
  provideGlobalConfig({ locale: zhCn }, app, true);
  for (const component of [
    ElAlert,
    ElAside,
    ElButton,
    ElCard,
    ElCheckbox,
    ElCheckboxGroup,
    ElCollapse,
    ElCollapseItem,
    ElContainer,
    ElDatePicker,
    ElDescriptions,
    ElDescriptionsItem,
    ElDialog,
    ElDrawer,
    ElDropdown,
    ElDropdownItem,
    ElDropdownMenu,
    ElForm,
    ElFormItem,
    ElHeader,
    ElInput,
    ElInputNumber,
    ElMain,
    ElMenu,
    ElMenuItem,
    ElOption,
    ElPagination,
    ElRadio,
    ElRadioButton,
    ElRadioGroup,
    ElSelect,
    ElSubMenu,
    ElSwitch,
    ElTabPane,
    ElTable,
    ElTableColumn,
    ElTabs,
    ElTag,
    ElTimePicker,
    ElTimeline,
    ElTimelineItem,
  ])
    app.component(component.name!, component);
  app.use(ElLoading).use(ElMessage).use(ElMessageBox);
}
